using System;

public class ForLoop
{
    public static void Main(String[] args)
    {
        
        //increment
        for(int i=1; i<=10; i++)
        {
            Console.WriteLine(i);
        }

        //decrement
        for(int i=10; i>=1; i--)
        {
            Console.WriteLine(i);
        }

    }
}